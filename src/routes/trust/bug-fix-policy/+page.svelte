		<h2>Scope</h2>

		<p>
			The following describes how and when we resolve security bugs in our products. It does not
			describe the complete disclosure or advisory process that we follow.
		</p>

		<h2>Security bug fix Service Level Objectives (SLO)</h2>

		<p>
			Realigned Technologies sets service level objectives for fixing security vulnerabilities based on the
			security severity level and the affected product. We have defined the following timeframes for
			fixing security issues in our products:
		</p>

		<h2>Resolution Timeframes</h2>

		<p>
			These timeframes apply to all of our products, and any other software or system that
			is managed by us, or is running on Realigned Technologies infrastructure.
		</p>

		<ul>
			<li>Critical severity bugs to be fixed in product within 1 weeks of being verified</li>
			<li>High severity bugs to be fixed in product within 2 weeks of being verified</li>
			<li>Medium severity bugs to be fixed in product within 4 weeks of being verified</li>
			<li>Low severity bugs to be fixed in product within 12 weeks of being verified</li>
		</ul>

		<h2>Critical Vulnerabilities</h2>

		<p>When a Critical security vulnerability is discovered by Realigned Technologies or reported by a third party,
			Realigned Technologies Ltd will deliver a bugfix release in accordance with the resolution timeframes described above.</p>

		<p>A bugfix release will always follow the newest version of the product. It is not recommended to use
			older versions of the product for any reason. We will inform customers about critical vulnerabilities via email,
			and if a bugfix release is announced, customers should upgrade to the newest version immediately.</p>

		<p>The critical vulnerabilities resolution process does not apply to apps built for Atlassian Cloud products as
			these services are always updated by Realigned Technologies without any additional action from customers.</p>

		<p>In order to fix critical vulnerabilities within the short timeframe described above, Realigned Technologies Ltd
			may temporarily limit or disable app functions affected by the vulnerability.</p>

