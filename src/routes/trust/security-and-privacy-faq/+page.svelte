		<h2>How does the application access Jira data (issues, projects, user information, etc)?</h2>

		<p>
			Denkplan Portfolio Maps for Jira is a client-side application which runs in the user's web browser.
			We do NOT access, copy or transfer any Jira data to our own infrastructure. All data manipulation is handled on
			the end-user machine with their own user credentials.
		</p>

		<h2>Which data does the application store and process?</h2>

		<p>
			In order to save application settings and personal preferences, the app uses Jira entity and app properties to store
			data in the Jira host instance. This is true for both Jira Cloud as well as Jira Data Center and Server.
		</p>

		<p>The following data is stored by the application in the Jira instance:</p>
		<ul>
			<li>A list of story maps per project</li>
			<li>Configuration data for each story map (can contain board ids and field ids)</li>
			<li>User preferences attached to the user profile</li>
			<li>Global settings</li>
		</ul>

		<p>The following data is stored on our infrastructure:</p>
		<ul>
			<li>Licensing information and the client keys required for the application to work</li>
		</ul>

		<h2>Do you collect and store personal identifying information (PII)?</h2>

		<p>
			Our applications do not store or process PII. We use analytics components that collect the user's ip address,
			however this information is not meant to identify the end-user and we do not collect any
			other PII or end-user data to make this information usable for this purpose.
		</p>

		<h2>Which analytics software is used by the application?</h2>

		<p>We collect application telemetry using PostHog, as well as error reports via Sentry.
			We use PostHog to measure feature usage, for example:</p>
		<ul>
			<li>How often is the application used in general?</li>
			<li>What percentage of users open the release notes?</li>
			<li>How often is a non-standard epic issue type configured?</li>
		</ul>

		<p>
			We use Sentry to collect error reports generated by the application in case of a
			major failure. In this case an error report with an overview of all requests and their status is
			sent to us. We anonymize all Jira data when sending this report.
		</p>

		<p>
			These components will stop working when you disable analytics in the app's global settings.
		</p>
