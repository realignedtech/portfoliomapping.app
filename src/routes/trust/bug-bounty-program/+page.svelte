		<h2>Introduction</h2>

		<p>
			Realigned Technologies has an active, private bug bounty program on Bugcrowd.com.
			In this document we want to outline the scope as well as the rewards, focus areas and remediation due dates of our
			bug bounty program for full transparency.
		</p>

		<h2>Scope</h2>

		<p>The following applications are in scope of the bug bounty program:</p>
		<ul>
			<li>Denkplan Portfolio Maps for Jira</li>
		</ul>

		<h2>Focus Areas</h2>

		<p>Below is a list of some of the vulnerability classes that we are seeking reports for:</p>
		<ul>
			<li>Cross Instance Data Leakage/Access</li>
			<li>Server-side Remote Code Execution (RCE)</li>
			<li>Server-Side Request Forgery (SSRF)</li>
			<li>Stored/Reflected Cross-site Scripting (XSS)</li>
			<li>Cross-site Request Forgery (CSRF)</li>
			<li>SQL Injection (SQLi)</li>
			<li>XML External Entity Attacks (XXE)</li>
			<li>Access Control Vulnerabilities (Insecure Direct Object Reference issues, etc)</li>
			<li>Path/Directory Traversal Issues</li>
		</ul>

		<h2>Rating and Rewards</h2>

		<p>We use BugCrowd's standard rating system for security vulnerabilities as well
			as Atlassian's defined reward scheme for the marketplace security program.
			Review the <a href="https://developer.atlassian.com/platform/marketplace/marketplace-security-bug-bounty-program/" target="_blank" rel="noreferrer">Atlassian Marketplace bug bounty program</a> for more information.</p>

		<h2>Remediation</h2>

		<p>We have defined our own bug fix policy which is more strict than the remediation due dates
			set by Atlassian. Review our <a href="/trust/bug-fix-policy">Bug Fix Policy</a> for the applicable timeframes.</p>

