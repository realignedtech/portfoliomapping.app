		<h2>Security Policy, Risk, and Governance</h2>

		<p>This policy sets out the general principles and guidelines for managing Security @ Realigned Technologies.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>We will manage access to company information and customer information based on business need</li>
			<li>We will implement a series of controls to manage the implementation of security in line with this policy</li>
			<li>We will periodically review risks and the effectiveness of controls intended to manage those risks</li>
			<li>We will maintain support for and show commitment in achieving compliance with applicable PII protection legislation and the contractual terms of cloud customers</li>
		</ul>

		<h2>Access Management</h2>

		<p>This policy sets out the general principles and guidelines for Access Management.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>We will maintain an Access Control policy outlining how to manage access to systems</li>
			<li>User accounts will be used to manage access</li>
			<li>All users have responsibility to manage access to their systems</li>
			<li>Systems will be logged and monitored for potential inappropriate access</li>
			<li>Remote access will be enabled via multi-factor authentication</li>
			<li>Duties should be segregated where appropriate</li>
		</ul>

		<h2>Asset Management</h2>

		<p>This policy sets out the general principles and guidelines for management of Realigned Technologies' (RT) IT assets and how those assets should be handled.</p>

		<p>The basic principles of asset management at RT include:</p>
		<ul>
			<li>We will maintain an inventory of assets</li>
			<li>Assets maintained in an asset management database will have identified owners</li>
			<li>Acceptable use of assets will be identified, documented and implemented</li>
			<li>Assets will be returned to RT if employment is terminated.</li>
		</ul>

		<h2>Cryptography & Encryption</h2>

		<p>This policy sets out the general principles to ensure that Realigned Technologies (RT) implements
			appropriate encryption & cryptography to ensure confidentiality and integrity of critical data.
			RT deploys cryptographic mechanisms to mitigate the risks involved in storing sensitive
			information and transmitting it over networks,
			including those that are publicly accessible (such as the internet).
			Facilitating the use of encryption technologies that are reliable,
			secure and proven to work effectively is a key objective of this standard in order to mitigate
			the risk of unauthorised access
			to and/or modification of sensitive company information.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>Sensitive data is encrypted appropriately</li>
			<li>Strength of selected encryption corresponds with information classification</li>
			<li>Cryptographic keys will be securely managed</li>
			<li>Only approved cryptographic algorithms and software modules will be used.</li>
		</ul>

		<h2>Operations</h2>

		<p>This policy sets out the general principles and guidelines for technology operational practices
			at Realigned Technologies.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>procedures should be documented for operational activities</li>
			<li>backups should be taken regularly and the backups tested</li>
			<li>changes should be managed and evaluated by multiple people</li>
			<li>capacity should be evaluated and planned for</li>
			<li>software installation should be limited and unnecessary software should be restricted</li>
		</ul>

		<h2>Personnel Security</h2>

		<p>This policy sets out the general principles and guidelines for personnel security at
			Realigned Technologies (RT).</p>

		<p>The basic principles include:</p>
		<ul>
			<li>Security responsibilities will be outlined in job definitions</li>
			<li>All employees and users will regularly view security awareness training</li>
			<li>All employees and contractors have a duty to report security incidents or weaknesses</li>
			<li>Upon employee termination, access and return of assets will occur in a reasonable time frame</li>
		</ul>

		<h2>Supplier Management</h2>

		<p>This policy sets out the general principles and guidelines to select, engage, monitor and
			off-board suppliers.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>RT will be purposeful in managing our vendor selection process</li>
			<li>RT will perform oversight of the relationship to ensure it meets our standards</li>
		</ul>

		<h2>Threat & Vulnerability Management</h2>

		<p>This policy sets out the general principles and guidelines for managing security threats and
			vulnerabilities both in our environment and in our products.</p>

		<p>The basic principles include:</p>
		<ul>
			<li>Manage security vulnerabilities in our products and services, including issuing updates, patches or advisories</li>
			<li>Manage security threats and vulnerabilities throughout our environment, both internal and hosted environments</li>
			<li>Manage the threat of malware in the environment</li>
		</ul>
